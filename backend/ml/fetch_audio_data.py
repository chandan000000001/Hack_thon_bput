def augment_piper(max_utterances: int) -> tuple[list[dict], dict | None]:
    """Synthesise VITS neural-TTS fakes offline with piper-tts. Never crashes."""
    try:
        import piper  # noqa: F401
    except ImportError:
        print("  piper-tts not installed; attempting uv pip install piper-tts ...")
        try:
            subprocess.run(
                [sys.executable, "-m", "pip", "install", "piper-tts"], check=True, capture_output=True
            )
        except Exception:
            try:
                subprocess.run(["uv", "pip", "install", "piper-tts"], check=True, capture_output=True, cwd=ML_DIR.parent)
            except Exception as exc:
                print(f"  WARN piper-tts install failed ({exc.__class__.__name__}); skipping augmentation")
                return [], None
        try:
            import piper  # noqa: F401
        except ImportError:
            print("  WARN piper-tts still unavailable (no wheel for this Python?); skipping augmentation")
            return [], None
    voice_dir = RAW_DIR / "piper_voice"
    voice_path = voice_dir / "en_US-lessac-medium.onnx"
    try:
        if not voice_path.exists():
            voice_dir.mkdir(parents=True, exist_ok=True)
            base = "https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_US/lessac/medium"
            download(f"{base}/en_US-lessac-medium.onnx", voice_path, timeout=300)
            download(f"{base}/en_US-lessac-medium.onnx.json", voice_dir / "en_US-lessac-medium.onnx.json")
    except Exception as exc:
        print(f"  WARN piper voice download failed ({exc.__class__.__name__}); skipping augmentation")
        return [], None
    try:
        import soundfile as sf

        from piper import PiperVoice

        voice = PiperVoice.load(str(voice_path))
        rows: list[dict] = []
        out_dir = DATA_DIR / "piper_tts" / "fake"
        out_dir.mkdir(parents=True, exist_ok=True)
        for index, sentence in enumerate(PIPER_SENTENCES[:max_utterances]):
            dest = out_dir / f"piper_{index:04d}.wav"
            if not dest.exists():
                with sf.SoundFile(str(dest), mode="w", samplerate=voice.config.sample_rate, channels=1, subtype="PCM_16") as fh:
                    voice.synthesize(sentence, fh)
            rows.append(
                {
                    "filepath": str(dest.relative_to(ML_DIR.parent)),
                    "label": 1,
                    "subclass": "piper_tts",
                    "partition": "train",
                    "source": "piper_tts_vits",
                }
            )
    except Exception as exc:
        print(f"  WARN piper synthesis failed ({exc.__class__.__name__}: {exc}); skipping augmentation")
        return [], None
    provenance = {
        "source": "piper_tts_vits",
        "url": "https://huggingface.co/rhasspy/piper-voices (en_US-lessac-medium)",
        "licence": "MIT — piper voices; sentences public domain",
        "status": "fetched",
        "rows": len(rows),
    }
    return rows, provenance



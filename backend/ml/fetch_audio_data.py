def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-utterances", type=int, default=2000, help="per-class cap (bonafide / spoof / per attack)")
    parser.add_argument("--augment-piper", action="store_true", help="optional piper-tts VITS fake augmentation")
    parser.add_argument("--source", choices=["auto", *SOURCE_CHAIN], default="auto")
    args = parser.parse_args()

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    RAW_DIR.mkdir(parents=True, exist_ok=True)

    manifest_path = DATA_DIR / "manifest.csv"
    existing_rows: list[dict] = []
    if manifest_path.exists():
        with manifest_path.open(newline="", encoding="utf-8") as fh:
            existing_rows = [row for row in csv.DictReader(fh) if row.get("filepath")]
    already_fetched = {row["source"] for row in existing_rows} - {"piper_tts_vits", "espeak_ng_synthetic"}

    rows = list(existing_rows)
    provenance_entries: dict[str, dict] = {}
    prov_path = DATA_DIR / "provenance.json"
    if prov_path.exists():
        provenance_entries = json.loads(prov_path.read_text(encoding="utf-8")).get("sources", {})

    chain = SOURCE_CHAIN if args.source == "auto" else [args.source]
    if args.source == "auto" and (RAW_DIR / "la_train.parquet").exists():
        # The research parquet mirror of the same ASVspoof 2019 LA data is
        # already on disk — skip the 7.6 GB official zip attempt.
        chain = ["hf_mirror", "wavefake", "espeak"]
    for source in chain:
        if source in already_fetched:
            print(f"  {source}: already recorded in the manifest, skipping")
            continue
        print(f"  trying source: {source}")
        try:
            fetched, prov = SOURCES[source](args.max_utterances)
        except Exception as exc:
            print(f"  WARN source {source} failed: {exc.__class__.__name__}: {exc}")
            continue
        if fetched:
            rows.extend(fetched)
            provenance_entries[source] = prov
            print(f"  {source}: {len(fetched)} utterances fetched")
            break

    if args.augment_piper:
        piper_rows, piper_prov = augment_piper(args.max_utterances)
        if piper_rows:
            piper_sources = {r["filepath"] for r in existing_rows if r["source"] == "piper_tts_vits"}
            rows.extend(r for r in piper_rows if r["filepath"] not in piper_sources)
            provenance_entries["piper_tts_vits"] = piper_prov

    if not rows:
        print("FAIL: no audio data could be fetched from any source in the chain")
        return 1

    # Deduplicate by filepath, write the manifest.
    unique = {r["filepath"]: r for r in rows}
    rows = list(unique.values())
    with manifest_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=["filepath", "label", "subclass", "partition", "source"])
        writer.writeheader()
        writer.writerows(sorted(rows, key=lambda r: r["filepath"]))

    real_world = setup_real_world_split()
    real_speech = export_real_speech_sample()
    provenance_entries["real_world_gate_split"] = {
        "source": "user-contributed clips",
        "path": str(REAL_WORLD_DIR.relative_to(REPO_ROOT)),
        "licence": "user-contributed (evaluation-only; NEVER trained on)",
        "status": "fetched",
        **real_world,
    }
    if real_speech:
        provenance_entries["real_speech_sample"] = {
            "source": "ASVspoof 2019 LA dev bonafide utterance",
            "path": str(real_speech),
            "status": "fetched",
        }
    prov_doc = {
        "version": 1,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "licence_note": "ASVspoof 2019 is released under the Open Data Commons Attribution Licence (ODC-By) 1.0 for academic/research use.",
        "sources": provenance_entries,
    }
    prov_path.write_text(json.dumps(prov_doc, indent=2), encoding="utf-8")

    counts: dict[str, int] = {}
    for row in rows:
        counts[row["subclass"]] = counts.get(row["subclass"], 0) + 1
    print(f"\nmanifest: {len(rows)} utterances across {len(counts)} subclasses")
    for subclass in sorted(counts):
        print(f"  {subclass:40s} {counts[subclass]:5d}")
    print(f"real-world gate split: fake={real_world['fake_clips']} real={real_world['real_clips']}")
    print(f"provenance: {prov_path}")
    return 0



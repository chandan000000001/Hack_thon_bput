def fetch_wavefake(max_utterances: int) -> tuple[list[dict], dict | None]:
    """WaveFake mirror: neural-vocoder fakes of LJSpeech + LJSpeech bona fide."""
    import pyarrow.parquet as pq
    import soundfile as sf

    parquet_path = RAW_DIR / "wavefake.parquet"
    download(WAVEFAKE_HF, parquet_path)
    rows: list[dict] = []
    reader = pq.ParquetFile(parquet_path)
    audio_col, label_col = None, None
    for batch in reader.iter_batches(batch_size=64):
        names = set(batch.schema.names)
        audio_col = next((n for n in names if "audio" in n.lower() or "bytes" in n.lower()), None)
        label_col = next((n for n in names if "label" in n.lower()), None)
        break
    if audio_col is None:
        raise FileNotFoundError("WaveFake mirror parquet has no audio column; cannot use fallback")
    for batch in reader.iter_batches(batch_size=64):
        columns = {name: batch.column(name).to_pylist() for name in batch.schema.names}
        for index, audio in enumerate(columns[audio_col]):
            fake = bool(columns[label_col][index]) if label_col else False
            if len([r for r in rows if r["label"] == (1 if fake else 0)]) >= max_utterances:
                continue
            dest = DATA_DIR / "wavefake" / ("fake" if fake else "real") / f"wf_{len(rows):06d}.flac"
            dest.parent.mkdir(parents=True, exist_ok=True)
            raw = io.BytesIO(audio["bytes"])
            with sf.SoundFile(raw) as handle:
                signal = handle.read(dtype="float32", always_2d=True).mean(axis=1)
                rate = handle.samplerate
            sf.write(dest, signal, rate, format="FLAC")
            rows.append(
                {
                    "filepath": str(dest.relative_to(ML_DIR.parent)),
                    "label": 1 if fake else 0,
                    "subclass": ("wavefake_fake" if fake else "wavefake_real"),
                    "partition": "train",
                    "source": "wavefake_hf_mirror",
                }
            )
    provenance = {
        "source": "wavefake_hf_mirror",
        "url": WAVEFAKE_HF,
        "licence": "CC BY-NC-SA 4.0 (WaveFake, research use)",
        "status": "fetched",
        "sha256": sha256_of(parquet_path),
        "rows": len(rows),
    }
    return rows, provenance



def fetch_espeak_fallback(max_utterances: int) -> tuple[list[dict], dict | None]:
    """Synthetic fakes via espeak-ng against any cached bona fide speech."""
    if shutil.which("espeak-ng") is None and shutil.which("espeak") is None:
        raise FileNotFoundError("espeak-ng is not installed; synthetic fallback unavailable")
    binary = shutil.which("espeak-ng") or shutil.which("espeak")
    bona_rows = []
    # Reuse any bona fide audio already extracted by an earlier attempt.
    for partition in ("train", "dev"):
        bona_dir = ASVSPOOF_DIR / partition / "bonafide"
        if bona_dir.exists():
            bona_rows.extend(sorted(bona_dir.glob("*")))
    real_dir = DATA_DIR / "espeak_fallback" / "real"
    if not bona_rows and real_dir.exists():
        bona_rows = sorted(real_dir.glob("*.wav"))
    if not bona_rows:
        raise FileNotFoundError("no cached bona fide speech for the espeak-ng fallback")
    rows: list[dict] = []
    fake_dir = DATA_DIR / "espeak_fallback" / "fake"
    fake_dir.mkdir(parents=True, exist_ok=True)
    for index, sentence in enumerate(PIPER_SENTENCES[:max_utterances]):
        dest = fake_dir / f"espeak_{index:04d}.wav"
        if not dest.exists():
            subprocess.run(
                [binary, "-v", "en-us", "-w", str(dest), sentence], check=True, capture_output=True
            )
        rows.append(
            {
                "filepath": str(dest.relative_to(ML_DIR.parent)),
                "label": 1,
                "subclass": "espeak_synthetic_fake",
                "partition": "train",
                "source": "espeak_ng_synthetic",
            }
        )
    for index, bona in enumerate(bona_rows[:max_utterances]):
        dest = real_dir / f"bona_{index:04d}.wav"
        if not dest.exists():
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(bona, dest)
        rows.append(
            {
                "filepath": str(dest.relative_to(ML_DIR.parent)),
                "label": 0,
                "subclass": "espeak_fallback_real",
                "partition": "train",
                "source": "espeak_ng_synthetic",
            }
        )
    provenance = {
        "source": "espeak_ng_synthetic",
        "url": "local espeak-ng synthesis (formant synthetic speech)",
        "licence": "generated locally — no external data",
        "status": "synthetic_fallback",
        "rows": len(rows),
    }
    return rows, provenance



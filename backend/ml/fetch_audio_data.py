# Source 2: HF parquet mirror of the same ASVspoof 2019 LA data
# ---------------------------------------------------------------------------

def fetch_hf_mirror(max_utterances: int) -> tuple[list[dict], dict | None]:
    """ASVspoof 2019 LA via the HuggingFace parquet research mirror.

    train-*.parquet -> LA train, validation-*.parquet -> LA dev.
    bonafide = system_id '-' ; spoof = attack system id (A01..A06).
    """
    import pyarrow.parquet as pq
    import soundfile as sf

    partitions = {
        "train": RAW_DIR / "la_train.parquet",
        "dev": RAW_DIR / "la_dev.parquet",
    }
    if not partitions["train"].exists():
        download(f"{HF_MIRROR}/train-00000-of-00001.parquet", partitions["train"])
    if not partitions["dev"].exists():
        download(f"{HF_MIRROR}/validation-00000-of-00001.parquet", partitions["dev"])

    rows: list[dict] = []
    for partition, parquet_path in partitions.items():
        attack_counts: dict[str, int] = {}
        bona_count = 0
        reader = pq.ParquetFile(parquet_path)
        for batch in reader.iter_batches(batch_size=256, columns=["speaker_id", "audio_file_name", "audio", "system_id"]):
            columns = {name: batch.column(name).to_pylist() for name in batch.schema.names}
            for speaker, file_name, audio, system_id in zip(
                columns["speaker_id"], columns["audio_file_name"], columns["audio"], columns["system_id"]
            ):
                bonafide = str(system_id).strip() in ("-", "")
                if bonafide:
                    if bona_count >= max_utterances:
                        continue
                else:
                    if attack_counts.get(str(system_id), 0) >= max_utterances // len(LA_ATTACKS) + 1:
                        continue
                subclass = "bonafide" if bonafide else str(system_id)
                if not file_name.endswith(".flac"):
                    file_name = f"{file_name}.flac"
                dest = ASVSPOOF_DIR / partition / subclass / file_name
                if not dest.exists():
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    try:
                        raw = io.BytesIO(audio["bytes"])
                        with sf.SoundFile(raw) as handle:
                            signal = handle.read(dtype="float32", always_2d=True).mean(axis=1)
                            rate = handle.samplerate
                        sf.write(dest, signal, rate, format="FLAC")
                    except Exception as exc:
                        print(f"    WARN skipping unreadable utterance {file_name}: {exc}")
                        continue
                if bonafide:
                    bona_count += 1
                else:
                    attack_counts[str(system_id)] = attack_counts.get(str(system_id), 0) + 1
                rows.append(
                    {
                        "filepath": str(dest.relative_to(ML_DIR.parent)),
                        "label": 0 if bonafide else 1,
                        "subclass": f"asvspoof2019_{partition}_{subclass}",
                        "partition": partition,
                        "source": "asvspoof2019_hf_mirror",
                    }
                )
            if bona_count >= max_utterances and all(
                c >= max_utterances // len(LA_ATTACKS) + 1 for c in attack_counts.values()
            ) and len(attack_counts) >= len(LA_ATTACKS):
                break
    provenance = {
        "source": "asvspoof2019_hf_mirror",
        "url": f"{HF_MIRROR}/train-00000-of-00001.parquet (+validation)",
        "licence": "ODC-By 1.0 — ASVspoof 2019 LA research mirror (same utterances as the official archive)",
        "status": "fetched",
        "sha256": sha256_of(partitions["train"]),
        "sha256_dev": sha256_of(partitions["dev"]),
        "rows": len(rows),
    }
    return rows, provenance



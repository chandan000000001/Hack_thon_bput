def setup_real_world_split() -> dict:
    fake_dir = REAL_WORLD_DIR / "fake"
    real_dir = REAL_WORLD_DIR / "real"
    fake_dir.mkdir(parents=True, exist_ok=True)
    real_dir.mkdir(parents=True, exist_ok=True)
    copied = []
    for candidate in ERCV_CANDIDATES:
        if candidate.exists():
            dest = fake_dir / "ercv.mp3"
            if not dest.exists():
                shutil.copy(candidate, dest)
            copied.append(str(dest))
            break
    note = (
        "User-contributed ElevenLabs clips (fake/) and voice memos (real/). "
        "NEVER used for training — evaluation-only gate split."
    )
    (REAL_WORLD_DIR / "README.md").write_text(
        f"# Real-world audio gate split\n\n{note}\n\n"
        "Gate metrics reported in ml/models/audio_v1_metrics.json.\n",
        encoding="utf-8",
    )
    return {
        "fake_clips": sorted(p.name for p in fake_dir.iterdir() if p.is_file()),
        "real_clips": sorted(p.name for p in real_dir.iterdir() if p.is_file()),
        "ercv_copied": bool(copied),
        "note": note,
    }


def export_real_speech_sample() -> str | None:
    """Copy one bona fide ASVspoof DEV utterance to evidence/media/real_speech.wav."""
    import soundfile as sf

    candidates = sorted((ASVSPOOF_DIR / "dev" / "bonafide").glob("*.flac")) if (ASVSPOOF_DIR / "dev" / "bonafide").exists() else []
    if not candidates:
        print("  WARN no bona fide dev utterance available for real_speech.wav")
        return None
    dest = EVIDENCE_MEDIA / "real_speech.wav"
    signal, rate = sf.read(candidates[0], dtype="float32")
    sf.write(dest, signal, rate, subtype="PCM_16")
    return str(dest)



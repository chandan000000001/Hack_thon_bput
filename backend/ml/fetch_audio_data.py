def fetch_official(max_utterances: int) -> tuple[list[dict], dict | None]:
    """ASVspoof 2019 LA from the official archive (selective extraction)."""
    import zipfile

    zip_path = RAW_DIR / "LA.zip"
    if not zip_path.exists():
        print("  downloading official LA.zip (~7.6 GB — the official mirror throttles; "
              "use --source hf_mirror for the research parquet mirror)")
        download(OFFICIAL_URL, zip_path, timeout=120)
    protocols = {
        "train": "ASVspoof2019_LA.cm.train.trn.txt",
        "dev": "ASVspoof2019_LA.cm.dev.trl.txt",
    }
    rows: list[dict] = []
    with zipfile.ZipFile(zip_path) as zf:
        names = set(zf.namelist())
        for partition, protocol in protocols.items():
            protocol_name = next((n for n in names if n.endswith(protocol)), None)
            if protocol_name is None:
                raise FileNotFoundError(f"protocol {protocol} not in archive")
            per_class: dict[str, int] = {"bonafide": 0, "spoof": 0}
            for line in zf.read(protocol_name).decode().strip().splitlines():
                parts = line.split()
                # utterance_id partition -(attack or '-')- label
                utterance_id, attack, label = parts[0], parts[2], parts[3]
                cls = "bonafide" if label == "bonafide" else "spoof"
                if per_class[cls] >= max_utterances:
                    continue
                subclass = cls if cls == "bonafide" else attack
                member = next(
                    (n for n in names if n.endswith(f"{utterance_id}.flac")), None
                )
                if member is None:
                    continue
                dest = ASVSPOOF_DIR / partition / ("bonafide" if cls == "bonafide" else "spoof") / f"{utterance_id}.flac"
                if not dest.exists():
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    dest.write_bytes(zf.read(member))
                rows.append(
                    {
                        "filepath": str(dest.relative_to(ML_DIR.parent)),
                        "label": 0 if cls == "bonafide" else 1,
                        "subclass": f"asvspoof2019_{partition}_{subclass}",
                        "partition": partition,
                        "source": "asvspoof2019_official",
                    }
                )
                per_class[cls] += 1
    provenance = {
        "source": "asvspoof2019_official",
        "url": OFFICIAL_URL,
        "licence": "ODC-By 1.0 (ASVspoof 2019, academic/research use)",
        "status": "fetched",
        "sha256": sha256_of(zip_path),
        "rows": len(rows),
    }
    return rows, provenance



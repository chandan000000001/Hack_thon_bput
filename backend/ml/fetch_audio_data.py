def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        while chunk := fh.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def download(url: str, dest: Path, timeout: int = 600) -> Path:
    """Stream a URL to disk with a one-line progress indicator."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    started = time.time()
    with urllib.request.urlopen(url, timeout=timeout) as resp, dest.open("wb") as out:
        total = int(resp.headers.get("Content-Length", 0)) or None
        done = 0
        while chunk := resp.read(1 << 22):
            out.write(chunk)
            done += len(chunk)
            if total:
                mbps = done / max(time.time() - started, 1e-6) / 1e6
                print(f"\r  {dest.name}: {done / 1e9:.2f}/{total / 1e9:.2f} GB ({mbps:.1f} MB/s)", end="", flush=True)
    print(f"\r  {dest.name}: downloaded {done / 1e9:.2f} GB in {time.time() - started:.0f}s")
    return dest



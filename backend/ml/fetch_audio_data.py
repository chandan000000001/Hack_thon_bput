"""Fetch audio deepfake training data (Audio Step 1).

Primary source: ASVspoof 2019 Logical Access (LA) train + dev partitions from
the official academic mirror (datashare.ed.ac.uk, the asvspoof.org download
endpoint — ODC-By 1.0 research licence). The official zip is ~7.6 GB and the
mirror throttles to ~180 KB/s, so the fetch chain also accepts a research
HuggingFace parquet mirror of the SAME ASVspoof 2019 LA data, used for
hackathon-scale runs:

    source chain (--source auto): official -> hf_mirror -> wavefake -> espeak

  1. official   — https://datashare.ed.ac.uk/.../LA.zip (selective zip extract,
                  capped per class by --max-utterances)
  2. hf_mirror  — HF dataset Bisher/ASVspoof_2019_LA parquet shards (train ->
                  LA train, validation -> LA dev); bona fide = system_id "-",
                  spoof = attack id A01..A06 (LA train/dev contain only the six
                  seen attacks; A07-A19 are the unseen eval attacks)
  3. wavefake   — WaveFake HuggingFace mirror (fake = neural-vocoder TTS of
                  LJSpeech text; real = LJSpeech bona fide)
  4. espeak_ng  — LAST RESORT: synthetic fakes synthesised locally with
                  espeak-ng against any bona fide audio already cached on
                  disk; provenance status becomes synthetic_fallback

Optional modern-TTS augmentation behind --augment-piper: synthesise neural
VITS fakes offline with piper-tts from 200 public-domain sentences (labelled
fake, subclass piper_tts). If the package or voice download cannot be
installed/used, the script warns and skips — it never crashes.

Real-world gate split (NEVER trained on, evaluation only):
    datasets/media/real_world_audio/fake/  user-contributed ElevenLabs clips
    datasets/media/real_world_audio/real/  user voice memos
A copy of the ElevenLabs clip ercv.mp3 is placed in fake/ when available.

Outputs:
    ml/data/audio/manifest.csv            filepath,label,subclass,partition,source
    ml/data/audio/provenance.json         per-source provenance (licence+status)
    ml/data/audio/asvspoof2019/<partition>/<subclass>/*.flac
    evidence/media/real_speech.wav        one bona fide ASVspoof dev utterance

Usage (from the backend directory):
    uv run python -m ml.fetch_audio_data --max-utterances 4000
    uv run python -m ml.fetch_audio_data --source hf_mirror --augment-piper
"""

